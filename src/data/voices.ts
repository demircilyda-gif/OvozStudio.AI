export function resolveCanonicalBaseVoice(voiceIdOrName?: string): BaseVoiceModel {
  const raw = String(voiceIdOrName || '').trim();
  if (!raw) return 'Charon';

  const lower = raw.toLowerCase();
  if (CANONICAL_BASE_MAP[lower]) {
    return CANONICAL_BASE_MAP[lower];
  }

  const profileMatch = PREBUILT_VOICE_PROFILES.find(
    (p) => p.id.toLowerCase() === lower || p.name.toLowerCase() === lower
  );
  if (profileMatch) {
    return profileMatch.baseVoice;
  }

  if (lower.includes('kore')) return 'Kore';
  if (lower.includes('aoede')) return 'Aoede';
  if (lower.includes('zephyr')) return 'Zephyr';
  if (lower.includes('fenrir')) return 'Fenrir';
  if (lower.includes('puck')) return 'Puck';
  if (lower.includes('charon')) return 'Charon';

  if (/aziza|madina|dilnoza|zarina|nodira|malika|sevara|shahnoza|rayhon|gulzoda|nilufar|ayol|female/i.test(lower)) {
    return 'Kore';
  }

  return 'Charon';
}
